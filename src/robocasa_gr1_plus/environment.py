from __future__ import annotations
import copy
import hashlib
from pathlib import Path
import subprocess
import numpy as np
from .embodiment import IMAGE_KEY, LANGUAGE_KEY, action_dict, format_observation
from .protocol import UPSTREAM_COMMIT, VISUAL, digest, env_name, variant, source_fingerprint
from .shifts import (visual_shift, corrupt_image, language_shift, state_snapshot,
                     array_digest, physical_digest, physical_initial_shift)

def source_provenance(root):
    root = Path(root).expanduser().resolve()
    try:
        revision = subprocess.check_output(["git","-C",str(root),"rev-parse","HEAD"],
                                           text=True,stderr=subprocess.DEVNULL).strip()
    except (OSError,subprocess.CalledProcessError) as exc:
        raise ValueError(f"Expected a pinned Git checkout at {root}") from exc
    if revision != UPSTREAM_COMMIT:
        raise ValueError(f"Use upstream revision {UPSTREAM_COMMIT}; found {revision}")
    dirty = subprocess.run(["git","-C",str(root),"diff","--quiet","HEAD","--","robocasa"],check=False)
    if dirty.returncode:
        raise ValueError("Upstream robocasa source is modified; use a clean pinned checkout")
    hashes = {}
    for path in sorted((root/"robocasa").rglob("*.py")):
        hashes[str(path.relative_to(root))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return {"commit":revision,"python_sources_sha256":digest(hashes)}

class GR1PlusEnvironment:
    """LoTTA environment interface using the official GR1 Gym and sensor preprocessing."""
    def __init__(self, cfg, episode):
        self.cfg, self.episode = cfg, episode
        if episode["benchmark"] != "robocasa_gr1_plus" or episode["upstream_commit"] != UPSTREAM_COMMIT:
            raise ValueError("Use a GR1 Plus manifest generated by gr1-plus plan")
        if episode.get("extension_sha256") != source_fingerprint():
            raise ValueError("GR1 Plus source differs from the manifest; generate a new plan/output")
        self.spec = variant(**episode["variant"])
        if episode.get("condition") != "clean":
            raise ValueError("The manifest variant already defines the shift; do not stack perturbations")
        if episode["env_name"] != env_name(episode["base_task_id"]):
            raise ValueError("Manifest task and GR1 environment name differ")
        pairing = episode.get("pairing")
        if pairing and (pairing != "gr1_visual_same_state" or episode["split"] != "calibration"
                        or self.spec["dimension"] not in VISUAL):
            raise ValueError("Only calibration visual episodes can expose paired observations")
        self.provenance = source_provenance(cfg["environment"]["expected_package_root"])
        import robocasa
        import robocasa.utils.gym_utils  # registers official Gym environments
        import gymnasium as gym
        root = Path(cfg["environment"]["expected_package_root"]).resolve()
        if root not in Path(robocasa.__file__).resolve().parents:
            raise ValueError("The imported robocasa package differs from expected_package_root")
        self.gym = gym.make(episode["env_name"],enable_render=True,seed=episode["seed"])
        self.base = self.gym.unwrapped
        self.suite = self.base.env
        self.sim = self.suite.sim
        self.max_steps = int(cfg["environment"].get("max_steps",720))
        self.steps = 0
        self._latest = None

    def _render_native(self):
        if self.suite.viewer_get_obs:
            raw = self.suite.viewer._get_observations(force_update=True)
        else:
            raw = self.suite._get_observations(force_update=True)
        # Retain the official vertical flip, crop 310:770/110:1130, resize and padding.
        basic = self.base.get_basic_observation(copy.deepcopy(raw))
        return self.base.get_groot_observation(basic)

    def _render(self, shifted):
        spec = self.spec if shifted else {"dimension":"clean","index":0,"severity":1}
        with visual_shift(self.sim,spec):
            native = self._render_native()
        return self._format_native(native,spec)

    def _format_native(self,native,spec):
        native[IMAGE_KEY] = corrupt_image(native[IMAGE_KEY],spec,self.episode["seed"],self.steps)
        native[LANGUAGE_KEY] = language_shift(native[LANGUAGE_KEY],spec)
        return format_observation(native)

    def reset(self):
        raw, _ = self.gym.reset(seed=self.episode["seed"])
        self.sim = self.suite.sim  # official hard_reset can replace the MjSim instance
        if self.spec["dimension"] in ("layout","robot_state"):
            self.provenance["initial_shift"] = physical_initial_shift(self.suite,self.spec)
        # Official GR1 reset already settles its scene. No LIBERO dummy gripper command.
        self.steps = 0
        self._latest = self._render(True)
        self.provenance.update({"env_name":self.episode["env_name"],
                               "initial_state_sha256":array_digest(state_snapshot(self.sim)),
                               "physical_model_sha256":physical_digest(self.sim),
                               "control_freq":self.suite.control_freq})
        return copy.deepcopy(self._latest)

    def pair(self):
        if self.episode.get("pairing") != "gr1_visual_same_state" or self._latest is None:
            raise ValueError("Paired reference observations are calibration-only")
        before = array_digest(state_snapshot(self.sim))
        physics = physical_digest(self.sim)
        clean = self._render(False)
        shifted = copy.deepcopy(self._latest)
        after = array_digest(state_snapshot(self.sim))
        if before != after or physics != physical_digest(self.sim):
            raise RuntimeError("Paired render altered simulation state or physical model")
        if not np.array_equal(clean["state"],shifted["state"]) or clean["language"] != shifted["language"]:
            raise RuntimeError("Paired visual samples differ in state or language")
        if np.array_equal(clean["primary"],shifted["primary"]):
            raise RuntimeError("Visual intervention is a no-op for this scene")
        self.pair_metadata = {"kind":"gr1_visual_same_state", "state_sha256":before,
            "physical_model_sha256":physics, "base_task_id":self.episode["base_task_id"],
            "variant_name":self.episode["variant_name"], "dimension":self.spec["dimension"],
            "native_wrapper_observation":True, "clean_rollout_executed":False}
        return clean, shifted

    def step(self, action):
        with visual_shift(self.sim,self.spec):
            raw, _, terminated, truncated, info = self.gym.step(action_dict(action))
        self.steps += 1
        self._latest = self._format_native(raw,self.spec)
        success = bool(info["success"])
        return copy.deepcopy(self._latest),success,bool(terminated or truncated or self.steps>=self.max_steps)

    def close(self):
        self.gym.close()
